export function branch(answers){
 const a=id=>answers.find(x=>x.id===id)?.choice;
 const first=['control','ban'].includes(a('T05'))?'T11':a('T04')==='continue'?'T13':'T06';
 const second=a('T07')==='friend'?'T14':a('T02')==='public'||a('T02')==='both'?'T12':['prison','life','death'].includes(a('T09'))?'T15':a('T03')==='record'?'T10':'T08';
 const last=['death','life'].includes(a('T17'))?'T18':'T19';
 return[first,second,last];
}
export function isSpecialEnd(t,kind){return !!t?.specialEnd?.includes(kind);}
export function validateAnswer(t,a){
 if(!t||!a)return false;
 const direct=t.options.some(o=>o.id===a.choice);
 if(!direct&&!['life','death'].includes(a.choice))return false;
 if(isSpecialEnd(t,a.choice))return false;
 if(t.sentencing){
  if(a.choice==='fine')return Number.isInteger(a.amount)&&a.amount>=1&&a.amount<=100000;
  if(a.choice==='prison')return Number.isInteger(a.years)&&a.years>=1&&a.years<=100;
  return direct;
 }
 if(['life','death'].includes(a.choice))return true;
 if(t.money&&(!Number.isFinite(a.amount)||a.amount<0||a.amount>t.money.max||a.amount%t.money.step!==0))return false;
 return true;
}
export function extremeText(kind){return kind==='death'?'死刑':'無期懲役';}
export function judgmentLabel(t,a){
 if(a.choice==='life'||a.choice==='death')return`有罪・${extremeText(a.choice)}`;
 if(t.sentencing){if(a.choice==='prison')return`有罪・懲役${a.years}年`;if(a.choice==='fine')return`有罪・罰金${Number(a.amount).toLocaleString()}万円`;}
 const choice=t.options.find(x=>x.id===a.choice)?.text??'';
 return(t.money?`${t.money.label}：${Number(a.amount).toLocaleString()}${t.money.unit} ／ `:'')+choice;
}
