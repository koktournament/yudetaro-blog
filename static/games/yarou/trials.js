export function evaluate(answers){
 const accepted=answers.filter(a=>validateAnswer(BY_ID[a.id],a));
 const axes=Object.fromEntries(Object.keys(AXES).map(k=>[k,{sum:0,n:0,ids:[]}]));
 for(const a of accepted){const t=BY_ID[a.id];if(t.sentencing||['life','death'].includes(a.choice))continue;const tags={...t.options.find(o=>o.id===a.choice).tags};
  if(t.money){const ratio=a.amount/t.money.base;tags.burden=ratio===0?-1:ratio<.5?-.5:ratio<=1?.25:1;tags.repair=ratio===0?0:.5;}
  for(const[k,v]of Object.entries(tags)){axes[k].sum+=v;axes[k].n++;axes[k].ids.push(t.id);}
 }
 for(const v of Object.values(axes)){v.value=v.n?v.sum/v.n:0;v.supported=v.n>=3;}
 return{axes,money:accepted.filter(a=>BY_ID[a.id].money&&!['life','death'].includes(a.choice)).map(a=>({id:a.id,amount:a.amount,ratio:a.amount/BY_ID[a.id].money.base,unit:BY_ID[a.id].money.unit})),criminal:accepted.filter(a=>BY_ID[a.id].sentencing||['life','death'].includes(a.choice)).map(a=>({id:a.id,choice:a.choice,years:a.years,amount:a.amount,label:judgmentLabel(BY_ID[a.id],a)})),count:accepted.length};
}
